n=int(input("Enter your marks::"))

if n<=100 and n>=90:
    print("your grade is A++")
elif n<=90 and n>=80:
    print("Your grade is A+")
elif n<=80 and n>=70:
    print("Your grade is A")
elif n<=70 and n>=60:
    print("Your grade is B+")
elif n<=60 and n>=50:
    print("your grade is B")
elif n<=50 and n>=40:
    print("Your grade is C")
else:
    print("Sorry you are fail, Better luck next time")                       